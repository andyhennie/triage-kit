// Writes dist/global/triage-kit.global.js from src/: one classic script that sets
// globalThis.TriageKit (and module.exports under node), for apps whose pages read the core
// from a plain <script>. ES-module apps import src/ directly. --check fails when it is stale.
// The classic script sits in dist/global/ beside a package.json that marks it CommonJS,
// because this package is type: module.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs'

const root=new URL('..',import.meta.url)
const {version}=JSON.parse(readFileSync(new URL('package.json',root),'utf8'))
const files=['selection','keys','batch','controller']
const body=files.map(f=>`// --- src/${f}.js\n`+readFileSync(new URL(`src/${f}.js`,root),'utf8')
  .replace(/^import [^\n]*from '\.\/[^']+'\n/gm,'').trim()).join('\n\n')
const names=[...body.matchAll(/^export (?:function|const) (\w+)/gm)].map(m=>m[1])
const head=`// triage-kit ${version} (generated by scripts/bundle.mjs from src/; do not edit). MIT.\n`
const global=head+`(function(){\n${body.replace(/^export /gm,'')}\nconst api={${names.join(',')}}\nif(typeof module==='object'&&module.exports)module.exports=api\nglobalThis.TriageKit=api\n})()\n`

const out={'dist/global/triage-kit.global.js':global,'dist/global/package.json':'{"type": "commonjs"}\n'}
if(process.argv.includes('--check')){
  const stale=Object.entries(out).filter(([p,s])=>{try{return readFileSync(new URL(p,root),'utf8')!==s}catch{return true}}).map(([p])=>p)
  if(stale.length){console.error(`stale: ${stale.join(', ')} (run node scripts/bundle.mjs)`);process.exit(1)}
}else{
  mkdirSync(new URL('dist/global/',root),{recursive:true})
  for(const [p,s] of Object.entries(out))writeFileSync(new URL(p,root),s)
}
